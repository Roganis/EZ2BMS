const nameOf = new Map(SDL_SCANCODE_NAMES.map(([s, n]) => [s, n] as const));
const codeOf = new Map<number, string>();
for (const [code, sc] of Object.entries(CODE_SCANCODE)) codeOf.set(sc, code);

/** SDL_GetScancodeFromName: 0 (unknown) when no key has that name. */
export function scancodeFromName(name: string): number {
  if (!name) return 0;
  for (const [sc, n] of SDL_SCANCODE_NAMES) if (asciiIeq(n, name)) return sc;
  return 0;
}

/** SDL_GetScancodeName: '' when SDL has no name for it. */
export function scancodeName(sc: number): string {
  return nameOf.get(sc) ?? '';
}

/** The KeyboardEvent.code a keys.ini key name means, if the browser has it. */
export function codeForKeyName(name: string): string | undefined {
  return codeOf.get(scancodeFromName(name));
}

/** The keys.ini name for a KeyboardEvent.code (what binding by pressing writes). */
export function keyNameForCode(code: string): string | undefined {
  const sc = CODE_SCANCODE[code];
  return sc === undefined ? undefined : scancodeName(sc) || undefined;
}
