// Keyboard key names: SDL's (what keys.ini spells, `Left Ctrl`, `;`) and the
// browser's (KeyboardEvent.code, `ControlLeft`, `Semicolon`). Both name the
// USB HID keyboard usage of the key, so each is a lookup by that number: a
// press the editor sees is matched to a binding written for EZ2PORT, which
// resolves names with SDL_GetScancodeFromName.
//
// SDL_SCANCODE_NAMES is SDL 3.4.16's own table (src/events/SDL_keymap.c
// SDL_scancode_names, zlib licence), which EZ2PORT's SDL 3.4.14 shares; the
// input crate's SDL test checks it against SDL_GetScancodeName. The lookup is
// SDL's: the first name equal ignoring ASCII case (Return is both 40 and 158;
// 40 wins).

